#!/usr/bin/env -S uv run python
"""Launch a local Home Assistant instance pointed at this integration.

Creates an ephemeral config directory under ``./.dev-ha`` (gitignored),
symlinks ``custom_components/switch_controlled_light`` into it, writes a
minimal ``configuration.yaml`` and starts ``hass`` with ``--dev``.

Usage:
    uv run scripts/develop.py
    uv run scripts/develop.py --no-start   # only set up the config dir
"""

from __future__ import annotations

import argparse
import os
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DEV_DIR = ROOT / ".dev-ha"
DOMAIN = "switch_controlled_light"


def write(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")


def setup() -> None:
    cc_src = ROOT / "custom_components" / DOMAIN
    cc_dst = DEV_DIR / "custom_components" / DOMAIN

    DEV_DIR.mkdir(exist_ok=True)
    (DEV_DIR / "custom_components").mkdir(exist_ok=True)

    if cc_dst.exists() or cc_dst.is_symlink():
        if cc_dst.is_symlink() or cc_dst.is_file():
            cc_dst.unlink()
        else:
            shutil.rmtree(cc_dst)
    os.symlink(cc_src, cc_dst)
    print(f"[dev] symlinked {cc_dst} -> {cc_src}")

    cfg = DEV_DIR / "configuration.yaml"
    if not cfg.exists():
        write(
            cfg,
            f"""# Auto-generated by scripts/develop.py — safe to delete with .dev-ha/.
default_config: !include_dir_named defaults/
python_dev_mode: true
logger:
  default: info
  logs:
    custom_components.{DOMAIN}: debug
""",
        )
        print(f"[dev] wrote {cfg}")

    (DEV_DIR / "defaults").mkdir(exist_ok=True)
    write(
        DEV_DIR / "defaults" / "homeassistant.yaml",
        """# Empty so default_config loads cleanly.
""",
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--no-start",
        action="store_true",
        help="Only prepare the dev config dir; do not start hass.",
    )
    args = parser.parse_args()

    setup()

    if args.no_start:
        print(f"[dev] ready: {DEV_DIR}")
        return 0

    cmd = [
        sys.executable,
        "-m",
        "homeassistant",
        "--config",
        str(DEV_DIR),
    ]
    print(f"[dev] launching: {' '.join(cmd)}")
    return subprocess.call(cmd, cwd=ROOT)


if __name__ == "__main__":
    raise SystemExit(main())

